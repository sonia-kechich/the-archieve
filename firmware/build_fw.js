/* ============================================================
   build_fw.js  —  turns the avr-gcc Intel-HEX output into the
   data avr8js needs, plus the sketch source for the code pane.

   For each level it:
     1. parses build/<dir>/<sketch>.ino.hex (Intel HEX, no bootloader)
        into a flat little-endian program-byte array,
     2. base64-encodes those bytes (avr8js loads them straight into
        the Uint16Array flash),
     3. reads the original .ino so the UI shows the real firmware.

   Output: ../js/firmware.js  (defines window.FW + window.FW_SRC)
   Run:    node firmware/build_fw.js
   ============================================================ */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LEVELS = [
  { key: 'blink', dir: 'l1_blink', sketch: 'l1_blink' },
  { key: 'btn', dir: 'l2_override', sketch: 'l2_override' },
  { key: 'alert', dir: 'l3_alert', sketch: 'l3_alert' },
];

// --- minimal Intel HEX parser -> Uint8Array of program bytes ---
function parseHex(text) {
  let bytes = [];
  let base = 0; // extended linear/segment base address
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line[0] !== ':') continue;
    const len = parseInt(line.substr(1, 2), 16);
    const addr = parseInt(line.substr(3, 4), 16);
    const type = parseInt(line.substr(7, 2), 16);
    const data = line.substr(9, len * 2);
    if (type === 0x00) {            // data record
      const at = base + addr;
      for (let i = 0; i < len; i++) {
        bytes[at + i] = parseInt(data.substr(i * 2, 2), 16);
      }
    } else if (type === 0x02) {     // extended segment address
      base = parseInt(data, 16) << 4;
    } else if (type === 0x04) {     // extended linear address
      base = parseInt(data, 16) << 16;
    } else if (type === 0x01) {     // EOF
      break;
    }
  }
  // fill any gaps with 0x00 so the flash image is contiguous
  const out = new Uint8Array(bytes.length);
  for (let i = 0; i < bytes.length; i++) out[i] = bytes[i] || 0;
  return out;
}

const FW = {};
const FW_SRC = {};
for (const L of LEVELS) {
  const hexPath = path.join(ROOT, 'build', L.dir, L.sketch + '.ino.hex');
  const inoPath = path.join(ROOT, 'firmware', L.dir, L.sketch + '.ino');
  const prog = parseHex(fs.readFileSync(hexPath, 'utf8'));
  FW[L.key] = Buffer.from(prog).toString('base64');
  FW_SRC[L.key] = fs.readFileSync(inoPath, 'utf8').replace(/\r\n/g, '\n').replace(/\s+$/, '');
  console.log(L.key.padEnd(6), prog.length + ' bytes ->', FW[L.key].length + ' b64 chars');
}

const banner = '/* AUTO-GENERATED by firmware/build_fw.js — do not edit by hand.\n' +
  '   Real ATmega328P firmware compiled with avr-gcc (arduino:avr).\n' +
  '   FW[key]     = base64 of the little-endian program image (avr8js flash)\n' +
  '   FW_SRC[key] = the exact .ino source shown in the FIRMWARE.NET pane */\n';
const body =
  banner +
  'window.FW = ' + JSON.stringify(FW) + ';\n' +
  'window.FW_SRC = ' + JSON.stringify(FW_SRC) + ';\n';
fs.writeFileSync(path.join(ROOT, 'js', 'firmware.js'), body);
console.log('wrote js/firmware.js');
